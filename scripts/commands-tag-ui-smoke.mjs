import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const baseURL = process.env.GRAFCET_TEST_URL || 'http://127.0.0.1:5173'
const browser = await chromium.launch(process.env.GRAFCET_TEST_EXECUTABLE ? { executablePath: process.env.GRAFCET_TEST_EXECUTABLE } : {})
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
await context.route('**/*', route => new URL(route.request().url()).origin === new URL(baseURL).origin && !new URL(route.request().url()).pathname.startsWith('/api/') ? route.continue() : route.abort())
await context.addInitScript(() => {
  localStorage.setItem('dcsimu:account:session:v1', 'dcsimu-admin')
  localStorage.removeItem('dcsimu:supabase:config:v1')
  globalThis.__dcAppImport = (path) => {
    const hit = performance.getEntriesByType('resource').map(e => e.name).filter(url => { try { return new URL(url).pathname === path } catch { return false } }).pop()
    return import(hit || path)
  }
})
const page = await context.newPage()
const errors = []
page.on('pageerror', e => errors.push(e.message))
const read = () => page.evaluate(async () => JSON.parse(JSON.stringify((await globalThis.__dcAppImport('/src/store/useSimStore.ts')).useSimStore.getState().commands)))
try {
  await page.goto(baseURL + '/dashboard')
  await page.getByRole('button', { name: 'Novo projeto', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('textbox', { name: 'Nome do projeto', exact: true }).fill('Referências IEC')
  await dialog.getByRole('radio', { name: /^Esquema IEC/ }).check()
  await dialog.getByRole('button', { name: 'Criar projeto', exact: true }).click()
  const canvas = page.locator('.dc-cmd-canvas')
  await canvas.waitFor()
  await page.getByRole('button', { name: 'Criar esquema IEC' }).click()
  const sidebar = page.locator('.dc-cmd-sidebar')
  await sidebar.getByRole('button', { name: 'Expandir', exact: true }).click()
  await sidebar.getByRole('button', { name: 'Colocar Fusível', exact: true }).first().click()
  const b = await canvas.boundingBox()
  await page.mouse.click(b.x + 300, b.y + 250)
  const before = await read()
  const part = before.parts[0]
  const label = page.locator(`[data-cmd-tag="${part.id}"]`)
  assert.equal(await label.getAttribute('text-anchor'), 'end')
  const labelBox = await label.boundingBox()
  const symbolBox = await page.locator(`[data-cmd-part="${part.id}"] .dc-cmd-symbol-hit`).boundingBox()
  assert(labelBox.x + labelBox.width < symbolBox.x + 1, 'referência à esquerda do símbolo')
  await page.mouse.move(labelBox.x + labelBox.width / 2, labelBox.y + labelBox.height / 2)
  await page.mouse.down()
  await page.mouse.move(labelBox.x + labelBox.width / 2 - 70, labelBox.y + labelBox.height / 2 + 40, { steps: 8 })
  await page.mouse.up()
  let current = await read()
  assert(current.parts[0].tagStyle?.x !== undefined, 'deslocamento guardado')
  assert.equal(current.parts[0].x, part.x)
  assert.equal(current.parts[0].y, part.y)
  assert.deepEqual(current.wires, before.wires)
  const moved = await label.boundingBox()
  assert(moved.x < labelBox.x - 50 && moved.y > labelBox.y + 20, 'referência move-se sem mover símbolo')
  await sidebar.getByRole('spinbutton', { name: 'Tamanho da referência' }).fill('24')
  await sidebar.getByRole('spinbutton', { name: 'Rotação da referência' }).fill('45')
  await sidebar.getByLabel('Cor da referência').fill('#d02040')
  current = await read()
  assert.equal(current.parts[0].tagStyle.fontSize, 24)
  assert.equal(current.parts[0].tagStyle.rotation, 45)
  assert.equal(current.parts[0].tagStyle.color, '#d02040')
  assert.match(await label.getAttribute('transform'), /rotate\(45 /)
  assert.match(await label.getAttribute('style'), /24px/)
  assert.match(await label.getAttribute('style'), /rgb\(208, 32, 64\)/)
  await sidebar.getByRole('button', { name: 'Repor referência' }).click()
  assert.equal((await read()).parts[0].tagStyle, undefined)
  assert.deepEqual(errors, [])
  console.log('PASS — referência à esquerda, arrastar, propriedades, cor e reposição no editor')
} finally { await browser.close() }
